"""Alerts presentation component for threat telemetry.

Includes severity breakdown chart with two-way Graph/Table switching,
severity filtering, and scannable alert cards.
"""

from collections import Counter
import html
import altair as alt
import pandas as pd
import streamlit as st

from .styles import apply_chart_theme, get_chart_palette, get_current_theme_mode


def render_alerts_section(alerts: list[dict]):
    """Render the Threat Alerts section with Graph/Table switching and severity cards."""
    st.markdown(
        """
        <div class="section-title">Threat Alerts & Behavioral Findings</div>
        <div class="section-subtitle">
            Rule-based detection indicators generated by the analysis module
        </div>
        """,
        unsafe_allow_html=True,
    )

    if not alerts:
        st.info("No security alerts generated for the events currently loaded.")
        return

    theme_mode = get_current_theme_mode()
    palette = get_chart_palette(theme_mode)

    alert_col1, alert_col2 = st.columns([1, 2])

    with alert_col1:
        head_col1, head_col2 = st.columns([2, 1])
        with head_col1:
            st.markdown(
                """
                <div class="chart-card-header">Severity Breakdown</div>
                <div class="chart-card-caption">Proportion of alerts across defined threat levels</div>
                """,
                unsafe_allow_html=True,
            )
        with head_col2:
            view_severity = st.segmented_control(
                "View mode for severity",
                options=["Graph", "Table"],
                default="Graph",
                key="view_severity_breakdown",
                label_visibility="collapsed",
            ) or "Graph"

        sev_counts = Counter(alert.get("severity") or "unknown" for alert in alerts)
        df_sev = pd.DataFrame([
            {"Severity": k, "Alert Count": v}
            for k, v in sev_counts.items()
        ])

        if view_severity == "Table":
            st.dataframe(df_sev, width="stretch", hide_index=True)
        else:
            donut_chart = alt.Chart(df_sev).mark_arc(
                innerRadius=46,
                outerRadius=75,
            ).encode(
                theta=alt.Theta("Alert Count:Q"),
                color=alt.Color(
                    "Severity:N",
                    scale=alt.Scale(
                        domain=["high", "medium", "low"],
                        range=[
                            palette["severity_high"],
                            palette["severity_med"],
                            palette["severity_low"],
                        ],
                    ),
                    legend=alt.Legend(title="Severity", orient="bottom"),
                ),
                tooltip=["Severity", "Alert Count"],
            ).properties(height=240)

            st.altair_chart(apply_chart_theme(donut_chart, theme_mode), width="stretch")

    with alert_col2:
        severity_options = ["All", "High", "Medium", "Low"]
        selected_sev = st.radio(
            "Filter alerts by severity:",
            options=severity_options,
            horizontal=True,
            index=0,
            key="alert_sev_filter",
        )

        filtered_alerts = alerts
        if selected_sev != "All":
            filtered_alerts = [
                a for a in alerts
                if str(a.get("severity") or "").lower() == selected_sev.lower()
            ]

        st.caption(f"Showing {len(filtered_alerts)} of {len(alerts)} alerts")

        alert_display_limit = 15
        for alert_item in filtered_alerts[:alert_display_limit]:
            sev = (alert_item.get("severity") or "low").lower()
            card_class = f"alert-card-{sev}"
            badge_class = f"badge-{sev}"
            rule_name = html.escape(str(alert_item.get("rule") or "unspecified_rule"))
            src_ip = html.escape(str(alert_item.get("src_ip") or "None"))
            session = html.escape(str(alert_item.get("session") or "None"))
            desc = html.escape(str(alert_item.get("description") or "No description provided."))
            ts = html.escape(str(alert_item.get("timestamp") or "No timestamp"))

            alert_card_html = f"""
            <div class="alert-card {card_class}">
                <div class="alert-header">
                    <div style="display: flex; align-items: center; gap: 8px;">
                        <span class="badge {badge_class}">{sev.upper()}</span>
                        <span class="alert-rule">{rule_name}</span>
                    </div>
                    <div class="alert-time">{ts}</div>
                </div>
                <div class="alert-desc">{desc}</div>
                <div class="alert-meta">
                    <span class="alert-meta-item"><b>Source IP:</b> {src_ip}</span>
                    <span class="alert-meta-item"><b>Session:</b> {session}</span>
                </div>
            </div>
            """
            st.markdown(alert_card_html, unsafe_allow_html=True)

        if len(filtered_alerts) > alert_display_limit:
            st.caption(f"Showing first {alert_display_limit} alerts. Use the table below to inspect all.")

    with st.expander("View Complete Alerts Data Table", expanded=False):
        alert_table_data = [
            {
                "Severity": alert.get("severity"),
                "Rule": alert.get("rule"),
                "Source IP": alert.get("src_ip"),
                "Session": alert.get("session"),
                "Timestamp": alert.get("timestamp"),
                "Description": alert.get("description"),
            }
            for alert in alerts
        ]
        st.dataframe(
            pd.DataFrame(alert_table_data),
            width="stretch",
            hide_index=True,
        )
